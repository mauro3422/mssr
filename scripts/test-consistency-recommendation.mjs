import assert from "node:assert/strict";

import { evaluateMssrConsistencyDecisionSupport } from "../dist/consistency-recommendation.js";

const canonical = {
  key: "bridge.release-version",
  observer: "package.json",
  role: "source",
  authority: "canonical",
  state: "observed",
  value: "0.6.104",
};

function decide(observations, boundary = "ordinary") {
  return evaluateMssrConsistencyDecisionSupport({ boundary, observations });
}

const healthy = decide([
  canonical,
  { key: "bridge.release-version", observer: "src/config.ts", role: "source", authority: "replica", state: "observed", value: "0.6.104", required: true },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.104", required: true },
  { key: "bridge.release-version", observer: "live-runtime", role: "runtime", authority: "replica", state: "observed", value: "0.6.104", required: true },
], "post-restart");
assert.equal(healthy.level, "ok");
assert.equal(healthy.recommendationPolicy, "evidence-first-v1");
assert.equal(healthy.recommendationMode, "none");
assert.equal(healthy.nextAction, null);
assert.deepEqual(healthy.recommendations, []);
assert.equal(healthy.repairDeferred, false);
assert.deepEqual(healthy.abstentionReasons, []);

const generatedAndRuntimeStale = decide([
  canonical,
  { key: "bridge.release-version", observer: "src/config.ts", role: "source", authority: "replica", state: "observed", value: "0.6.104", required: true },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.103", required: true },
  { key: "bridge.release-version", observer: "live-runtime", role: "runtime", authority: "replica", state: "observed", value: "0.6.103", required: true },
], "post-restart");
assert.equal(generatedAndRuntimeStale.level, "error");
assert.equal(generatedAndRuntimeStale.nextAction, "rebuild-generated-artifact", "known-good source plus stale generated/runtime should repair generated bytes first");
assert.equal(generatedAndRuntimeStale.recommendationMode, "repair");
const rebuild = generatedAndRuntimeStale.recommendations.find((item) => item.action === "rebuild-generated-artifact");
const verifyRuntime = generatedAndRuntimeStale.recommendations.find((item) => item.action === "verify-live-runtime");
assert.ok(rebuild);
assert.ok(verifyRuntime);
assert.equal(rebuild.status, "ready");
assert.equal(rebuild.confidence, "high");
assert.equal(rebuild.reasonCodes.includes("generated-replica-proven-stale"), true);
assert.equal(verifyRuntime.status, "deferred");
assert.deepEqual(verifyRuntime.dependsOn, ["rebuild-generated-artifact"]);
assert.equal(verifyRuntime.blockedBy.includes("generated-artifact-stale"), true);
assert.equal(generatedAndRuntimeStale.repairDeferred, false, "a ready rebuild means repair itself is not deferred");
assert.deepEqual(generatedAndRuntimeStale.recommendedActions, generatedAndRuntimeStale.recommendations.map((item) => item.action));

const sourceUnproven = decide([
  canonical,
  { key: "bridge.release-version", observer: "src/config.ts", role: "source", authority: "replica", state: "unknown", required: true },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.103", required: true },
], "pre-release");
assert.equal(sourceUnproven.nextAction, "inspect-source-replica", "do not rebuild generated output while the source replica itself is unproven");
const blockedRebuild = sourceUnproven.recommendations.find((item) => item.action === "rebuild-generated-artifact");
assert.ok(blockedRebuild);
assert.equal(blockedRebuild.status, "deferred");
assert.deepEqual(blockedRebuild.dependsOn, ["inspect-source-replica"]);
assert.equal(blockedRebuild.blockedBy.includes("source-replica-unproven"), true);
assert.equal(sourceUnproven.repairDeferred, true);

const canonicalConflict = decide([
  canonical,
  { ...canonical, observer: ".mssr/PROJECT_STATE.md", role: "state", value: "0.6.105" },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.103", required: true },
], "pre-release");
assert.equal(canonicalConflict.level, "error");
assert.equal(canonicalConflict.nextAction, "inspect-canonical-authorities");
assert.equal(canonicalConflict.recommendations[0].confidence, "high");
assert.equal(canonicalConflict.recommendations[0].reasonCodes.includes("resolve-authority-before-repair"), true);

const historical = decide([
  canonical,
  { key: "bridge.release-version", observer: "receipt:old", role: "receipt", authority: "historical", state: "observed", value: "0.6.99" },
], "context-load");
assert.equal(historical.level, "review");
assert.equal(historical.nextAction, "revalidate-context-evidence", "historical disagreement should first seek current evidence, not blindly replan");
assert.equal(historical.recommendationMode, "investigate");
assert.ok(historical.recommendations.findIndex((item) => item.action === "revalidate-context-evidence") < historical.recommendations.findIndex((item) => item.action === "review-stale-claim"));
assert.ok(historical.recommendations.findIndex((item) => item.action === "review-stale-claim") < historical.recommendations.findIndex((item) => item.action === "replan-current-context"));

const installedStale = decide([
  { key: "bridge.mssr-package-version", observer: "package.json#dependencies.@mauroprime/mssr", role: "source", authority: "canonical", state: "observed", value: "0.2.24" },
  { key: "bridge.mssr-package-version", observer: "node_modules/@mauroprime/mssr/package.json", role: "installed", authority: "replica", state: "observed", value: "0.2.23", required: true },
], "post-restart");
assert.equal(installedStale.nextAction, "refresh-installed-artifact");
assert.equal(installedStale.recommendationMode, "repair");
assert.equal(installedStale.recommendations[0].risk, "high");
assert.equal(installedStale.recommendations[0].cost, "medium");
assert.equal(installedStale.recommendations[0].blastRadius, "high");
assert.ok(installedStale.recommendations[0].scoreBreakdown.blastRadiusPenalty < 0);
assert.equal(installedStale.recommendations[0].confidence, "high");
assert.equal(installedStale.recommendations[0].advisoryOnly, true);

const missingBaseline = decide([
  { key: "project.context-revision", observer: "receipt:resume", role: "receipt", authority: "historical", state: "observed", revision: "rev-11" },
], "context-load");
assert.equal(missingBaseline.level, "watch");
assert.equal(missingBaseline.nextAction, "load-canonical-authority");
assert.equal(missingBaseline.recommendationMode, "investigate");
assert.equal(missingBaseline.recommendations[0].confidence, "high");
assert.equal(missingBaseline.recommendations[0].reasonCodes.includes("canonical-baseline-missing"), true);

const empty = decide([], "pre-execution");
assert.equal(empty.level, "watch");
assert.equal(empty.recommendationMode, "abstain");
assert.equal(empty.nextAction, null);
assert.deepEqual(empty.recommendations, []);
assert.deepEqual(empty.abstentionReasons, ["consistency-evidence-empty"]);

const shuffledA = decide([
  canonical,
  { key: "bridge.release-version", observer: "src/config.ts", role: "source", authority: "replica", state: "observed", value: "0.6.104", required: true },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.103", required: true },
  { key: "bridge.release-version", observer: "live-runtime", role: "runtime", authority: "replica", state: "observed", value: "0.6.103", required: true },
], "post-restart");
const shuffledB = decide([
  { key: "bridge.release-version", observer: "live-runtime", role: "runtime", authority: "replica", state: "observed", value: "0.6.103", required: true },
  { key: "bridge.release-version", observer: "dist/config.js", role: "generated", authority: "replica", state: "observed", value: "0.6.103", required: true },
  canonical,
  { key: "bridge.release-version", observer: "src/config.ts", role: "source", authority: "replica", state: "observed", value: "0.6.104", required: true },
], "post-restart");
assert.deepEqual(shuffledB.recommendations, shuffledA.recommendations, "C2d ranking must be independent from caller observation ordering");
assert.equal(shuffledB.nextAction, shuffledA.nextAction);

for (const recommendation of generatedAndRuntimeStale.recommendations) {
  assert.ok(recommendation.score >= 0 && recommendation.score <= 100);
  assert.equal(typeof recommendation.scoreBreakdown.attention, "number");
  assert.equal(recommendation.advisoryOnly, true);
}

console.log("MSSR C2d evidence-first consistency recommendations: PASS");
